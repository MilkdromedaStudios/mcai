"""Write a LiteLLM proxy config from the keys saved in PyFlayer, with automatic fallbacks.

LiteLLM (https://github.com/BerriAI/litellm) is an OpenAI-compatible router: PyFlayer talks to one address
(provider "litellm", http://localhost:4000/v1, model "pyflayer") and LiteLLM spreads the requests over all your
providers, retries, and jumps to the next one when one is rate-limited.

    pip install 'litellm[proxy]'
    python -m pyflayer litellm-config          # writes data/litellm_config.yaml
    litellm --config data/litellm_config.yaml  # then pick provider "litellm" in Settings
"""
from __future__ import annotations

from .llm import PROVIDERS

PREFIX = {"groq": "groq", "gemini": "gemini", "openrouter": "openrouter", "openai": "openai",
          "anthropic": "anthropic", "mistral": "mistral", "deepseek": "deepseek", "together": "together_ai",
          "xai": "xai"}
FREE_MODELS = {
    "groq": ["llama-3.3-70b-versatile", "llama-3.1-8b-instant"],
    "gemini": ["gemini-2.5-flash", "gemini-2.0-flash"],
    "openrouter": ["meta-llama/llama-3.3-70b-instruct:free", "deepseek/deepseek-chat-v3-0324:free"],
}


def _q(v: str) -> str:
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(cfg) -> str:
    llm = cfg["llm"]
    keys = dict(llm.get("keys") or {})
    if llm.get("api_key") and llm.get("provider") not in keys:
        keys[llm.get("provider")] = llm["api_key"]
    deployments = []          # (group, litellm model, key, api_base)
    for prov, key in keys.items():
        if prov not in PREFIX or not key:
            continue
        models = FREE_MODELS.get(prov) or [PROVIDERS[prov]["model"]]
        if llm.get("provider") == prov and llm.get("model"):
            models = [llm["model"], *[m for m in models if m != llm["model"]]]
        for i, m in enumerate(models):
            deployments.append(("pyflayer" if i == 0 else "pyflayer-backup", f"{PREFIX[prov]}/{m}", key, None))
    local = cfg.get("training.local") or {}
    deployments.append(("pyflayer-local", f"ollama_chat/{local.get('model') or 'qwen2.5:3b'}", None,
                        (local.get("base_url") or "http://localhost:11434").removesuffix("/v1")))
    if not any(d[0] == "pyflayer" for d in deployments):
        raise RuntimeError("no saved API keys yet - add them in Settings first (local Ollama is still included)")
    out = ["# Generated by PyFlayer. Start with:  litellm --config data/litellm_config.yaml",
           "# In PyFlayer Settings choose provider 'litellm' (model 'pyflayer').", "model_list:"]
    for group, model, key, base in deployments:
        out += [f"  - model_name: {group}", "    litellm_params:", f"      model: {_q(model)}"]
        if key:
            out.append(f"      api_key: {_q(key)}")
        if base:
            out.append(f"      api_base: {_q(base)}")
    out += ["router_settings:", "  routing_strategy: simple-shuffle", "  num_retries: 2", "  allowed_fails: 1",
            "  cooldown_time: 60",
            "  fallbacks: [{\"pyflayer\": [\"pyflayer-backup\", \"pyflayer-local\"]}]",
            "  context_window_fallbacks: [{\"pyflayer\": [\"pyflayer-backup\"]}]",
            "litellm_settings:", "  drop_params: true", "  request_timeout: 120"]
    return "\n".join(out) + "\n"
